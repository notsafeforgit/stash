const bootstrapFixtureVersion = 1000121
const bootstrapFixturePath = "bootstrap/1000121.sql"

// Replay the actual empty historical input, including registered Go migrations.
// This deliberately never uses Database.Open on an empty database: that is the
// independent initialization path whose result this test must verify.
func replayBootstrapHistory(t *testing.T, path string, version uint) {
	t.Helper()
	config.InitializeEmpty()
	raw := openRawDB(t, path)
	initial, err := os.ReadFile("migrations/1_initial.up.sql")
	require.NoError(t, err)
	_, err = raw.Exec(string(initial))
	require.NoError(t, err)
	driver, err := sqlite3mig.WithInstance(raw, &sqlite3mig.Config{})
	require.NoError(t, err)
	require.NoError(t, driver.SetVersion(1, false))
	require.NoError(t, driver.Close())
	db := sqlite.NewDatabase()
	var needed *sqlite.MigrationNeededError
	require.ErrorAs(t, db.Open(path), &needed)
	m, err := sqlite.NewMigrator(db)
	require.NoError(t, err)
	defer m.Close()
	for m.CurrentSchemaVersion() < version {
		require.NoError(t, m.RunMigration(context.Background(), m.GetNextMigrationVersion(m.CurrentSchemaVersion())))
	}
	require.Equal(t, version, m.CurrentSchemaVersion())
}

func sqlIdentifier(name string) string {
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

func bootstrapValues(t *testing.T, raw *sql.DB, query string, args ...any) []string {
	t.Helper()
	rows, err := raw.Query(query, args...)
	require.NoError(t, err)
	defer rows.Close()
	var values []string
	for rows.Next() {
		var value string
		require.NoError(t, rows.Scan(&value))
		values = append(values, value)
	}
	require.NoError(t, rows.Err())
	return values
}

func bootstrapObjects(t *testing.T, raw *sql.DB) []string {
	t.Helper()
	// Include implicit indexes and sqlite_sequence, which cannot be emitted as
	// standalone DDL. ANALYZE's statistics are the only optimization artifacts.
	return bootstrapValues(t, raw, `SELECT quote(type)||','||quote(name)||','||quote(tbl_name)||','||quote(sql)
FROM sqlite_schema WHERE name NOT GLOB 'sqlite_stat[134]' ORDER BY type,name`)
}

// Preserve SQLite's stored DDL verbatim, including inline constraints, defaults,
// partial indexes and triggers. Initial rows are emitted before triggers so
// they cannot accidentally manufacture other initial rows. Only migration
// timestamps vary per installation; no library records or UUIDs are normalized.
func bootstrapSnapshot(t *testing.T, raw *sql.DB) string {
	t.Helper()
	rows, err := raw.Query(`SELECT type, name, sql FROM sqlite_schema
WHERE sql IS NOT NULL AND name NOT GLOB 'sqlite_*'
ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, name`)
	require.NoError(t, err)
	defer rows.Close()
	var tables, definitions, afterData []string
	for rows.Next() {
		var kind, name, definition string
		require.NoError(t, rows.Scan(&kind, &name, &definition))
		if kind == "table" {
			tables = append(tables, name)
		}
		if kind == "trigger" {
			afterData = append(afterData, definition+";\n")
		} else {
			definitions = append(definitions, definition+";\n")
		}
	}
	require.NoError(t, rows.Err())
	// sqlite_sequence is created implicitly by AUTOINCREMENT tables. Its rows
	// also form part of the historical empty database's initial state.
	if rawTableExists(t, raw, "sqlite_sequence") {
		tables = append(tables, "sqlite_sequence")
		definitions = append(definitions, "DELETE FROM sqlite_sequence;\n")
	}
	for _, table := range tables {
		var names, values []string
		for _, column := range bootstrapValues(t, raw, "SELECT name FROM pragma_table_info(?) ORDER BY cid", table) {
			names = append(names, sqlIdentifier(column))
			if (table == "native_schema" && column == "promoted_at") ||
				((table == "legacy_schema_history" || table == "native_migration_history") && column == "applied_at") {
				values = append(values, "'CURRENT_TIMESTAMP'")
			} else {
				values = append(values, "quote("+sqlIdentifier(column)+")")
			}
		}
		var inserts []string
		for _, value := range bootstrapValues(t, raw, "SELECT "+strings.Join(values, " || ',' || ")+" FROM "+sqlIdentifier(table)) {
			inserts = append(inserts, fmt.Sprintf("INSERT INTO %s (%s) VALUES (%s);\n", sqlIdentifier(table), strings.Join(names, ","), value))
		}
		sort.Strings(inserts)
		definitions = append(definitions, inserts...)
	}
	definitions = append(definitions, afterData...)
	return "-- Code generated by TestNativeBootstrapBaselineMatchesMigrations; DO NOT EDIT.\n" +
		"-- Regenerate: STASH_REGENERATE_NATIVE_BASELINE=1 go test ./pkg/sqlite -run '^TestNativeBootstrapBaselineMatchesMigrations$' -count=1\n" +
		"-- Pinned native schema 1000121; later migrations run normally.\n\n" + strings.Join(definitions, "\n")
}

func TestNativeBootstrapBaselineMatchesMigrations(t *testing.T) {
	path := filepath.Join(t.TempDir(), "historical.sqlite")
	replayBootstrapHistory(t, path, bootstrapFixtureVersion)
	raw := openRawDB(t, path)
	defer raw.Close()
	want := bootstrapSnapshot(t, raw)
	if os.Getenv("STASH_REGENERATE_NATIVE_BASELINE") == "1" {
		require.NoError(t, os.MkdirAll(filepath.Dir(bootstrapFixturePath), 0755))
		require.NoError(t, os.WriteFile(bootstrapFixturePath, []byte(want), 0644))
	}
	actual, err := os.ReadFile(bootstrapFixturePath)
	require.NoError(t, err)
	require.Equal(t, want, string(actual), "the generated native baseline has drifted from its migrations")

	// Execute the snapshot as well: a textual dump alone cannot prove that its
	// dependency order, implicit indexes or initial rows can be reconstructed.
	direct := openRawDB(t, filepath.Join(t.TempDir(), "direct.sqlite"))
	defer direct.Close()
	_, err = direct.Exec("PRAGMA foreign_keys=OFF")
	require.NoError(t, err)
	tx, err := direct.Begin()
	require.NoError(t, err)
	defer func() { _ = tx.Rollback() }()
	_, err = tx.Exec(string(actual))
	require.NoError(t, err)
	require.NoError(t, tx.Commit())
	require.Equal(t, want, bootstrapSnapshot(t, direct))
	require.Equal(t, bootstrapObjects(t, raw), bootstrapObjects(t, direct))
	var integrity string
	require.NoError(t, direct.QueryRow("PRAGMA integrity_check").Scan(&integrity))
	require.Equal(t, "ok", integrity)
	var violation any
	require.ErrorIs(t, direct.QueryRow("SELECT 1 FROM pragma_foreign_key_check LIMIT 1").Scan(&violation), sql.ErrNoRows)
}

func TestNativeBootstrapCurrentSchemaMatchesMigrations(t *testing.T) {
	path := filepath.Join(t.TempDir(), "historical.sqlite")
	replayBootstrapHistory(t, path, sqlite.GetRequiredSchemaVersion())
	historical := openRawDB(t, path)
	defer historical.Close()
	want := bootstrapSnapshot(t, historical)

	path = filepath.Join(t.TempDir(), "direct.sqlite")
	db := sqlite.NewDatabase()
	require.NoError(t, db.Open(path))
	require.NoError(t, db.Close())
	direct := openRawDB(t, path)
	defer direct.Close()
	require.Equal(t, want, bootstrapSnapshot(t, direct), "baseline plus subsequent migrations must equal a complete historical replay")
	require.Equal(t, bootstrapObjects(t, historical), bootstrapObjects(t, direct))
}
