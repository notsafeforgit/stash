#!/usr/bin/env node
// Generates src/components/settings/settings-search-index.gen.ts from the
// settings route files: every `<Setting* label={msg("id", "default")} ...>`
// row becomes a search entry tagged with its page route and enclosing
// `<SettingsSection title={...}>`.
//
// Run as `pnpm run gen-settings-index` after adding/removing settings rows.
// The check-i18n gate keeps the referenced ids honest; this script keeps the
// search index from rotting by hand-maintenance.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const routesDir = join(root, "src/routes/settings");
const outFile = join(
  root,
  "src/components/settings/settings-search-index.gen.ts",
);

// msg("id", "default") with the default possibly spanning lines after
// formatting. Collapse whitespace first so one regex handles both shapes.
const MSG = String.raw`msg\(\s*"([^"]+)",\s*"((?:[^"\\]|\\.)*)",?\s*\)`;
const SECTION_RE = new RegExp(
  String.raw`<SettingsSection\s+title=\{${MSG}\}`,
  "g",
);
const ROW_RE = new RegExp(
  String.raw`<Setting(?:Text|Path|Switch|Select|Number|StringList|Display)\b[^>]*?label=\{${MSG}\}(?:[^>]*?description=\{${MSG}\})?`,
  "g",
);

const entries = [];

for (const file of readdirSync(routesDir).sort()) {
  if (!file.endsWith(".tsx") || file === "index.tsx") continue;
  const route = `/settings/${file.replace(/\.tsx$/, "")}`;
  const src = readFileSync(join(routesDir, file), "utf8").replace(/\s+/g, " ");

  // Section boundaries: list of [position, {id, default}] then assign each
  // row to the latest section that starts before it.
  const sections = [];
  for (const m of src.matchAll(SECTION_RE)) {
    sections.push({ pos: m.index, id: m[1], def: m[2] });
  }

  for (const m of src.matchAll(ROW_RE)) {
    const section = sections.filter((s) => s.pos < m.index).at(-1) ?? null;
    entries.push({
      to: route,
      section: section ? { id: section.id, defaultMessage: section.def } : null,
      label: { id: m[1], defaultMessage: m[2] },
      ...(m[3] ? { description: { id: m[3], defaultMessage: m[4] } } : {}),
    });
  }
}

const header = `// Generated by scripts/generate-settings-search-index.mjs — do not edit.
// Regenerate with \`pnpm run gen-settings-index\` after changing settings rows.

export interface SettingsSearchMessage {
  id: string;
  defaultMessage: string;
}

export interface SettingsSearchEntry {
  /** Settings page route the row lives on. */
  to: string;
  /** Enclosing SettingsSection title, when there is one. */
  section: SettingsSearchMessage | null;
  label: SettingsSearchMessage;
  description?: SettingsSearchMessage;
}

export const SETTINGS_SEARCH_INDEX: SettingsSearchEntry[] = `;

writeFileSync(outFile, header + JSON.stringify(entries, null, 2) + ";\n");
console.log(`wrote ${entries.length} entries to ${outFile}`);
